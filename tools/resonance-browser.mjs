import {chromium} from 'playwright';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {activateCooperation} from '../web/src/utils/divinityCooperation.js';
import {freshDivinity} from '../web/src/utils/divinitySave.js';
import {SAVE_KEY} from '../web/src/utils/storage.js';
const projectRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),root=path.join(projectRoot,'dist');
const server=createServer(async(req,res)=>{
 try{
  const route=decodeURIComponent(new URL(req.url,'http://127.0.0.1').pathname);
  const file=route==='/standalone'?path.join(projectRoot,'irena-play.html'):path.resolve(root,'.'+(route==='/'?'/index.html':route));
  if(route==='/standalone'?file!==path.join(projectRoot,'irena-play.html'):!file.startsWith(root+path.sep)){res.writeHead(403);res.end();return;}
  const content=await readFile(file);
  const type=file.endsWith('.html')?'text/html':file.endsWith('.js')?'text/javascript':file.endsWith('.css')?'text/css':file.endsWith('.webp')?'image/webp':'application/octet-stream';
  res.writeHead(200,{'Content-Type':type});res.end(content);
 }catch{res.writeHead(404);res.end();}
});
await new Promise(ok=>server.listen(0,'127.0.0.1',ok));
const base='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({headless:true});
let page;
try{
 page=await browser.newPage({viewport:{width:1280,height:800},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base);
 const s=activateCooperation(freshDivinity());
 s.started=true;s.floor=20;s.cleared=Array.from({length:20},(_,i)=>i+1);
 s.stats.atk=5000;s.stats.hp=1000;
 s.divinity.infiniteWins=1;s.summonPoints=1000;s.p=1000;
 await page.evaluate(([key,raw])=>localStorage.setItem(key,raw),[SAVE_KEY,JSON.stringify(s)]);
 await page.reload();
 await page.waitForTimeout(250);
 if(await page.locator('button.navbtn[data-id=upgrade]').count()===0){
  const body=(await page.locator('body').textContent()||'').slice(0,800);
  const stored=await page.evaluate(key=>localStorage.getItem(key)?.slice(0,180),SAVE_KEY);
  const script=await page.locator('script').last().textContent();
  throw Error('No navigation rendered; decl='+script.includes('function summonBalance')+'; summonDef='+script.includes('SUMMON_COST_SINGLE')+'; idx='+script.indexOf('summonBalance')+'; scriptLength='+script.length+'; body='+body.slice(0,90)+'; saved='+stored+'; errors='+errors.join('; '));
 }
 await page.locator('button.navbtn[data-id=upgrade]').click();
 await page.locator('button.upgrade-category[data-id=summon]').click();
 await page.locator('button[data-action=resonanceSummon][data-id="10"]').click();
 const modal=page.locator('dialog[open]');
 await modal.waitFor();
 if(!(await modal.textContent()).includes('共鳴召喚 10回'))throw Error('Ten-pull result missing');
 const stored=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),SAVE_KEY);
 if(stored.summonPoints!==100||stored.resShards<45)throw Error('Ten-pull reward/currency not persisted');
 await modal.locator('button[data-action=close]').click();
 await page.locator('button[data-action=resonanceSummon][data-id="1"]').click();
 await page.locator('dialog[open]').waitFor();
 const afterSingle=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),SAVE_KEY);
 if(afterSingle.summonPoints!==0)throw Error('Single summon did not debit exactly 100P');
 await page.locator('dialog[open] button[data-action=close]').click();
 await page.reload();
 const afterReload=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),SAVE_KEY);
 if(afterReload.summonPoints!==0||afterReload.resShards<45)throw Error('Summon save did not survive reload');
 const shardsBeforeTrial=afterReload.resShards;
 await page.locator('button.navbtn[data-id=home]').click();
 const trial=page.locator('button[data-action=resTrialStart]');
 await trial.waitFor();
 await trial.click();
 await page.getByText('黒翼を狩る白騎士').first().waitFor();
 await page.locator('button[data-action=divCommand][data-id=feather]').click();
 await page.waitForFunction(()=>document.documentElement.dataset.combatBusy==='false');
 const hpBeforeReload=await page.locator('.div-hp-enemy .div-hp-value').textContent();
 const savedBattle=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),SAVE_KEY);
 if(savedBattle.markBattle?.schema!==4||savedBattle.markBattle.turns.length!==1)throw Error('Resonance trial turn was not checkpointed');
 await page.reload();
 await page.getByRole('button',{name:/戦闘に戻る/}).click();
 await page.getByText('黒翼を狩る白騎士').first().waitFor();
 const hpAfterReload=await page.locator('.div-hp-enemy .div-hp-value').textContent();
 if(hpAfterReload!==hpBeforeReload)throw Error('Resonance trial did not resume at saved HP');
 await page.goto(base+'/standalone');
 await page.getByRole('button',{name:/戦闘に戻る/}).click();
 await page.getByText('黒翼を狩る白騎士').first().waitFor();
 const standaloneCheckpoint=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),SAVE_KEY);
 if(standaloneCheckpoint.markBattle?.schema!==4||await page.locator('.div-hp-enemy .div-hp-value').textContent()!==hpAfterReload)throw Error('Standalone build did not resume the active trial checkpoint');
 await page.goto(base);
 await page.getByRole('button',{name:/戦闘に戻る/}).click();
 await page.getByText('黒翼を狩る白騎士').first().waitFor();
 await page.setViewportSize({width:390,height:844});
 const mobile=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,commands:document.querySelector('.div-commands'),arena:document.querySelector('.div-arena')}));
 if(mobile.scrollWidth>mobile.width+1)throw Error('Mobile layout overflows horizontally: '+mobile.scrollWidth+'/'+mobile.width);
 if(!mobile.commands||mobile.commands.scrollHeight>mobile.commands.clientHeight+1)throw Error('Mobile combat commands require scrolling');
 await page.locator('button[data-action=divCommand][data-id=slash]').click();
 await page.waitForFunction(()=>document.documentElement.dataset.combatBusy==='false');
 if(!(await page.locator('.div-objective').textContent()).includes('共闘成功'))throw Error('First cooperative breakthrough did not appear in the trial objective');
 await page.locator('.div-page-next').click();
 for(let i=0;i<10&&await page.locator('button[data-action=divCommand][data-id=res_wingjudge]').count()===0;i++)await page.locator('.div-page-next').click();
 await page.locator('button[data-action=divCommand][data-id=res_wingjudge]').click();
 await page.locator('.result h2').waitFor();
 if(await page.locator('.result h2').innerText()!=='VICTORY')throw Error('Initial resonance activation did not clear its event battle');
 const learned=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),SAVE_KEY);
 if(learned.divinity.resonanceV3.levels.wingjudge!==1||!learned.divinity.resonanceV3.cleared.includes(1)||learned.divinity.resonanceV3.floor!==2)throw Error('First event did not grant its resonance exactly once and advance the trial');
 if(learned.resShards!==shardsBeforeTrial+12||learned.summonPoints!==0)throw Error('Trial reward leaked into summon currency or changed the expected shard reward');
 await page.setViewportSize({width:1280,height:800});
 await page.goto(base+'/standalone');
 await page.waitForSelector('button.navbtn[data-id=upgrade]');
 const standalone=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),SAVE_KEY);
 if(standalone.divinity.resonanceV3.levels.wingjudge!==1||standalone.resShards!==shardsBeforeTrial+12)throw Error('Standalone bundle did not load the settled resonance trial save');
 if(errors.length)throw Error('Browser errors: '+errors.join('; '));
 console.log('Resonance browser smoke: summon, currency persistence, trial checkpoint/resume, mobile layout, standalone bundle SUCCESS');
}finally{await page?.close();await browser.close();await new Promise(ok=>server.close(ok));}
